const { chromium, devices } = require("playwright");
const install = require("./mock.cjs");
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices["iPhone 13"], colorScheme: "dark" });
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await install(page);
  await page.addInitScript(() => localStorage.setItem("crate:yt", "no"));
  await page.goto("http://localhost:8787/");
  await page.waitForSelector("text=45 Platten");
  await page.click(".nav >> text=Sammlung");
  await page.waitForTimeout(1200);
  await page.evaluate(() => window.scrollTo(0, 1500));
  await page.waitForTimeout(600);
  await page.screenshot({ path: __dirname + "/nav1-scrolled.png" });
  const y1 = await page.evaluate(() => window.scrollY);
  const target = page.locator(".rec").nth(14);
  await target.scrollIntoViewIfNeeded();
  await page.waitForTimeout(300);
  const yBefore = await page.evaluate(() => window.scrollY);
  console.log("y before click", yBefore);
  await target.click();
  await page.waitForTimeout(1200);
  console.log("url", page.url(), "scroll on detail", await page.evaluate(() => window.scrollY));
  await page.goBack();
  await page.waitForTimeout(1500);
  console.log("restored", y1, "->", await page.evaluate(() => window.scrollY), "highlight", !!(await page.$(".last-tapped")));
  await page.screenshot({ path: __dirname + "/nav2-back.png" });
  await page.goto("http://localhost:8787/gibtsnicht");
  await page.waitForTimeout(600);
  console.log("404", !!(await page.$("text=Seite nicht gefunden")));
  console.log("errors", errors);
  await b.close();
})();
