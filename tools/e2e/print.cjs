const { chromium, devices } = require("playwright");
const install = require("./mock.cjs");
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices["iPhone 13"], colorScheme: "light" });
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await install(page);
  await page.addInitScript(() => localStorage.setItem("crate:yt", "no"));
  await page.goto("http://localhost:8787/");
  await page.waitForSelector("text=45 Platten"); await page.waitForTimeout(1500);
  await page.goto("http://localhost:8787/stickers?ids=5,9,2");
  await page.waitForTimeout(1500);
  await page.click("text=Laden").catch(() => {});
  await page.waitForSelector("text=ohne Tracklist", { state: "detached", timeout: 60000 }).catch(() => console.log("tracklists still missing"));
  await page.click(".seg >> text=Farbe");
  await page.click(".seg >> text=Klassisch");
  await page.click("[aria-label='Akzentfarbe #0a84ff']");
  await page.fill("input[placeholder='Aus der Kiste von …']", "Aus der Kiste von DJ Franz");
  await page.waitForTimeout(1500);
  await page.screenshot({ path: __dirname + "/print1.png" });
  await page.click(".seg >> text=Weiß");
  await page.click(".seg >> text=Modern");
  await page.waitForTimeout(800);
  await page.emulateMedia({ media: "print" });
  await page.pdf({ path: __dirname + "/print.pdf", printBackground: true, preferCSSPageSize: true });
  console.log("errors", errors);
  await b.close();
})();
