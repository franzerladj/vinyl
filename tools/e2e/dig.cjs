const { chromium, devices } = require("playwright");
const install = require("./mock.cjs");
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices["iPhone 13"], colorScheme: "dark" });
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("console", (m) => m.type() === "error" && errors.push("console: " + m.text().slice(0, 120)));
  const wants = [];
  page.on("request", (r) => r.url().includes("/wants/") && r.method() === "PUT" && wants.push(r.url()));
  await install(page);
  await page.addInitScript(() => localStorage.setItem("crate:yt", "no"));
  await page.goto("http://localhost:8787/");
  await page.waitForSelector("text=45 Platten");
  await page.screenshot({ path: __dirname + "/dig0-home.png" });
  await page.click("text=Jetzt diggen");
  await page.waitForSelector(".dig-card .dig-title", { timeout: 30000 });
  await page.waitForTimeout(2500);
  console.log("cards", await page.locator(".dig-card").count(), "nav visible", await page.isVisible(".nav"));
  await page.screenshot({ path: __dirname + "/dig1.png" });
  const t1 = await page.locator(".dig-card").nth(0).getAttribute("aria-label");
  await page.evaluate(() => document.querySelector(".dig-feed").scrollBy({ top: innerHeight }));
  await page.waitForTimeout(1500);
  const box = await page.locator(".dig-card").nth(1).locator(".dig-stage").boundingBox();
  await page.mouse.dblclick(box.x + box.width / 2, box.y + box.height / 2);
  await page.waitForTimeout(400);
  await page.screenshot({ path: __dirname + "/dig2.png" });
  await page.waitForTimeout(1500);
  // Doppeltippen = Mag ich: kein Wantlist-Aufruf, Daumen ist an
  console.log("first", t1, "want calls (soll 0)", wants.length, "gemocht", await page.locator(".dig-bar .on.like").count());
  console.log("errors", errors);
  await b.close();
})();
